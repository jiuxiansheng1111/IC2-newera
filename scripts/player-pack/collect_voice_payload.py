"""Collect the explicitly configured local voice runtime for a private test pack.

This module is deliberately a manifest builder: it never copies files, starts a
process, downloads assets, or reads QQ credentials.  The caller may stream the
returned file sources and generated bytes into a private archive.
"""
from __future__ import annotations

import ast
import hashlib
import json
import os
import re
from pathlib import Path, PurePosixPath
from typing import Any, Iterable


RUNTIME_CONFIG = Path("tools/robot_voice/ic2newera-voice-runtime.json")
VOICE_CODE = (
    "configuration.py",
    "cover_mixer.py",
    "engine.py",
    "japanese_frontend.py",
    "resources.py",
    "runtime_support.py",
    "rvc_worker.py",
    "separation_worker.py",
    "server.py",
    "tts_worker.py",
    "start_voice.ps1",
)
PYTHON_ROOTS = {
    # GPT-SoVITS' tools.portable_runtime resolves its runtime under the code
    # root, so CPython lives in this subdirectory of the requested bundle root.
    "tts": "portable/python-tts/runtime",
    "rvc": "portable/python-rvc",
    "singing": "portable/python-singing",
}
EXCLUDED_DIRS = {
    "__pycache__",
    ".git",
    ".hg",
    ".svn",
    ".pytest_cache",
    ".mypy_cache",
    ".ruff_cache",
    ".cache",
    "cache",
    "caches",
    "log",
    "logs",
    "output",
    "outputs",
    "temp",
    "tmp",
}
SECRET_NAME_RE = re.compile(
    r"(^\.env(?:\..*)?$|(?:api[_-]?key|secret[_-]?key|access[_-]?token|refresh[_-]?token)|"
    r"(^|[._-])id_rsa($|[._-])|\.(?:key|pem|p12|pfx)$)",
    re.IGNORECASE,
)
ABSOLUTE_WINDOWS_PATH_RE = re.compile(r"(?i)(?:[a-z]:[\\/]|file:///+[a-z]:/)")


def _read_json(path: Path) -> dict[str, Any]:
    value = json.loads(path.read_text(encoding="utf-8-sig"))
    if not isinstance(value, dict):
        raise ValueError("The explicit voice runtime config is not a JSON object.")
    return value


def _configured_path(config_path: Path, value: Any, field: str) -> Path:
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"Required configured path is missing: {field}")
    candidate = Path(value).expanduser()
    if not candidate.is_absolute():
        candidate = config_path.parent / candidate
    return candidate.resolve(strict=True)


def _safe_target(relative: str) -> str:
    path = PurePosixPath(relative.replace("\\", "/"))
    if path.is_absolute() or any(part in ("", ".", "..") for part in path.parts):
        raise ValueError(f"Invalid package target: {relative!r}")
    result = PurePosixPath("tools/robot_voice", *path.parts).as_posix()
    if not result.startswith("tools/robot_voice/"):
        raise ValueError("Voice payload target escaped its permitted prefix.")
    return result


def _file_hash(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _static_torch_version(site_packages: Path) -> dict[str, Any] | None:
    """Read literal assignments from torch/version.py without importing torch."""
    source = site_packages / "torch" / "version.py"
    if not source.is_file():
        return None
    try:
        tree = ast.parse(source.read_text(encoding="utf-8"), filename="torch/version.py")
    except (OSError, UnicodeError, SyntaxError):
        return {"available": True, "parsed": False}
    fields: dict[str, Any] = {}
    for node in tree.body:
        if not isinstance(node, (ast.Assign, ast.AnnAssign)):
            continue
        value_node = node.value
        targets = node.targets if isinstance(node, ast.Assign) else [node.target]
        names = [target.id for target in targets if isinstance(target, ast.Name)]
        if not names or value_node is None:
            continue
        try:
            value = ast.literal_eval(value_node)
        except (ValueError, TypeError, SyntaxError):
            continue
        if names[0] in {"__version__", "cuda", "hip", "git_version", "debug"}:
            if isinstance(value, (str, int, float, bool, type(None))):
                fields[names[0]] = value
    return {"available": True, "parsed": True, **fields}


def _distribution_versions(site_packages: Path) -> dict[str, str]:
    """Read package/version names from dist-info directory names only."""
    result: dict[str, str] = {}
    if not site_packages.is_dir():
        return result
    for entry in site_packages.glob("*.dist-info"):
        stem = entry.name[: -len(".dist-info")]
        match = re.match(r"^(.+?)-([0-9][^/]*)$", stem)
        if match:
            package = re.sub(r"[-_.]+", "-", match.group(1)).casefold()
            result[package] = match.group(2)
    return result


def _is_secret_name(name: str) -> bool:
    return bool(SECRET_NAME_RE.search(name))


def _should_skip_path(path: Path) -> bool:
    if any(part.casefold() in EXCLUDED_DIRS for part in path.parts):
        return True
    if path.suffix.casefold() in (".pyc", ".pyo"):
        return True
    if _is_secret_name(path.name) and path.suffix.casefold() != ".py" and path.name.casefold() != "cacert.pem":
        return True
    return False


def _tree_files(root: Path, on_symlink: Any = None, skip_root_dirs: Iterable[str] = ()) -> Iterable[Path]:
    """Yield regular files only; symlinks are reported instead of followed."""
    skip_root_dirs = {name.casefold() for name in skip_root_dirs}
    for current, dirs, files in os.walk(root, topdown=True, followlinks=False):
        current_path = Path(current)
        kept_dirs = []
        for name in dirs:
            if current_path == root and name.casefold() in skip_root_dirs:
                continue
            child = current_path / name
            if _should_skip_path(child.relative_to(root)):
                continue
            if child.is_symlink():
                if on_symlink:
                    on_symlink(child.relative_to(root).as_posix())
                continue
            kept_dirs.append(name)
        dirs[:] = kept_dirs
        for name in files:
            candidate = current_path / name
            if _should_skip_path(candidate.relative_to(root)) or candidate.is_symlink():
                if candidate.is_symlink() and on_symlink:
                    on_symlink(candidate.relative_to(root).as_posix())
                continue
            if candidate.is_file():
                yield candidate


def _venv_info(python: Path, label: str) -> dict[str, Any]:
    if python.name.casefold() not in ("python.exe", "pythonw.exe"):
        raise ValueError(f"{label} interpreter is not a Windows Python executable.")
    venv_root = python.parent.parent.resolve(strict=True)
    cfg = venv_root / "pyvenv.cfg"
    if not cfg.is_file():
        raise ValueError(f"{label} pyvenv.cfg is missing.")
    # Read only the three fields needed to resolve the base runtime.  In
    # particular, do not expose or preserve the recorded creation command.
    fields: dict[str, str] = {}
    for line in cfg.read_text(encoding="utf-8", errors="replace").splitlines():
        if "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.strip().casefold()
        if key in {"home", "executable", "version"}:
            fields[key] = value.strip()
    home = fields.get("home")
    version = fields.get("version")
    if not home or not version:
        raise ValueError(f"{label} pyvenv.cfg lacks home/version metadata.")
    base = Path(home).resolve(strict=True)
    base_python = base / "python.exe"
    if not base_python.is_file():
        raise ValueError(f"{label} base runtime does not contain python.exe.")
    recorded_executable = fields.get("executable")
    executable_relation = "not_recorded"
    if recorded_executable:
        recorded = Path(recorded_executable)
        try:
            executable_relation = (
                "matches_home_python"
                if recorded.resolve(strict=True) == base_python.resolve(strict=True)
                else "different_from_home_python"
            )
        except OSError:
            executable_relation = "recorded_executable_missing"
    return {
        "label": label,
        "venv_version": version,
        "base_runtime": base,
        "base_version": version,
        "venv_root": venv_root,
        "site_packages": venv_root / "Lib" / "site-packages",
        "executable_relation": executable_relation,
    }


def collect_voice_payload(project_root: Path) -> dict[str, Any]:
    """Return source file mappings and generated files for a private voice pack.

    Every target key is rooted under ``tools/robot_voice/``.  Source values are
    absolute local paths as required by the packager interface.  Metadata is
    intentionally free of local source paths, credentials, prompts, and logs.
    """
    project_root = Path(project_root).resolve(strict=True)
    tools_root = project_root / "tools" / "robot_voice"
    config_path = project_root / RUNTIME_CONFIG
    if not tools_root.is_dir() or not config_path.is_file():
        raise FileNotFoundError("First-party robot voice runtime/config was not found.")
    config = _read_json(config_path)

    blockers: list[str] = []
    notes: list[str] = []
    optional_limits: list[str] = []
    excluded: dict[str, int] = {}
    files: dict[str, Path] = {}
    generated: dict[str, bytes] = {}
    source_groups: dict[str, list[str]] = {}
    target_sources: dict[str, Path] = {}
    symlink_skips: dict[str, list[str]] = {}

    def symlink_skipped(group: str, relative: str) -> None:
        entries = symlink_skips.setdefault(group, [])
        if len(entries) < 50:
            entries.append(relative)

    def record_excluded(reason: str) -> None:
        excluded[reason] = excluded.get(reason, 0) + 1

    def add_source(relative_target: str, source: Path, group: str) -> None:
        target = _safe_target(relative_target)
        source = source.resolve(strict=True)
        if not source.is_file():
            blockers.append(f"missing file for {target}")
            return
        target_key = target.casefold()
        prior_source = target_sources.get(target_key)
        prior_generated = next((key for key in generated if key.casefold() == target_key), None)
        if prior_source is not None or prior_generated is not None:
            if prior_source is not None:
                identical = prior_source.resolve() == source.resolve() or (
                    prior_source.stat().st_size == source.stat().st_size
                    and _file_hash(prior_source) == _file_hash(source)
                )
            else:
                identical = (
                    len(generated[prior_generated]) == source.stat().st_size
                    and hashlib.sha256(generated[prior_generated]).hexdigest() == _file_hash(source)
                )
            if not identical:
                blockers.append(f"case-insensitive target collision at {target}")
            return
        files[target] = source
        target_sources[target_key] = source
        source_groups.setdefault(group, []).append(target)

    def add_generated(relative_target: str, contents: bytes, group: str) -> None:
        target = _safe_target(relative_target)
        target_key = target.casefold()
        prior_source = target_sources.get(target_key)
        prior_generated = next((key for key in generated if key.casefold() == target_key), None)
        if prior_source is not None or prior_generated is not None:
            if prior_source is not None:
                identical = (
                    prior_source.stat().st_size == len(contents)
                    and _file_hash(prior_source) == hashlib.sha256(contents).hexdigest()
                )
            else:
                identical = generated[prior_generated] == contents
            if not identical:
                blockers.append(f"generated target collision at {target}")
            return
        generated[target] = contents
        source_groups.setdefault(group, []).append(target)

    def copy_tree(
        source_root: Path,
        target_root: str,
        group: str,
        *,
        include: Any = None,
        exclude: Any = None,
        skip_root_dirs: Iterable[str] = (),
    ) -> None:
        source_root = source_root.resolve(strict=True)
        if not source_root.is_dir():
            blockers.append(f"missing directory for {group}")
            return
        for source in _tree_files(source_root, lambda item: symlink_skipped(group, item), skip_root_dirs):
            relative = source.relative_to(source_root)
            if include is not None and not include(relative, source):
                record_excluded(f"not_selected:{group}")
                continue
            if exclude is not None and exclude(relative, source):
                record_excluded(f"excluded_by_policy:{group}")
                continue
            add_source((PurePosixPath(target_root) / PurePosixPath(*relative.parts)).as_posix(), source, group)

    def copy_pth_site_packages(
        site_packages: Path,
        target_root: str,
        group: str,
        *,
        external_site_map: dict[str, tuple[Path, str]],
    ) -> None:
        """Copy a full site-packages tree while rewriting known path entries.

        ``.pth`` import lines are retained only when they contain no absolute
        path.  Known path-only references to another bundled site-packages tree
        become relative .pth entries.  Unresolved executable/path entries are
        omitted and reported as blockers.
        """
        site_packages = site_packages.resolve(strict=True)
        target_site = PurePosixPath(target_root)
        for source in _tree_files(site_packages, lambda item: symlink_skipped(group, item)):
            relative = source.relative_to(site_packages)
            rel_text = relative.as_posix()
            if source.name.casefold() == "direct_url.json":
                record_excluded(f"installer_provenance:{group}")
                continue
            if source.suffix.casefold() == ".egg-link":
                blockers.append(f"editable install source was excluded: {group}/{rel_text}")
                record_excluded(f"editable_link:{group}")
                continue
            target_rel = (target_site / PurePosixPath(*relative.parts)).as_posix()
            if source.suffix.casefold() != ".pth" or relative.parent != Path("."):
                add_source(target_rel, source, group)
                continue
            if group == "site_packages_singing" and source.name.casefold() == "shared_gpu_runtime.pth":
                # Rewritten below after all portable site-package locations
                # have been fixed; never package its original absolute path.
                record_excluded("rewritten_absolute_shared_gpu_pth")
                continue

            try:
                text = source.read_text(encoding="utf-8", errors="strict")
            except (OSError, UnicodeError):
                blockers.append(f"unreadable .pth was excluded: {group}/{rel_text}")
                record_excluded(f"unreadable_pth:{group}")
                continue
            rewritten: list[str] = []
            unresolved_lines: list[int] = []
            for line_number, raw_line in enumerate(text.splitlines(), 1):
                stripped = raw_line.strip()
                if not stripped or stripped.startswith("#"):
                    if stripped and ABSOLUTE_WINDOWS_PATH_RE.search(stripped):
                        unresolved_lines.append(line_number)
                    else:
                        rewritten.append(raw_line)
                    continue
                if stripped.startswith("import ") or stripped.startswith("import\t"):
                    if ABSOLUTE_WINDOWS_PATH_RE.search(stripped):
                        unresolved_lines.append(line_number)
                    else:
                        rewritten.append(raw_line)
                    continue
                entry = Path(stripped)
                if entry.is_absolute():
                    resolved = entry.resolve(strict=False)
                    mapped = external_site_map.get(str(resolved).casefold())
                    if mapped:
                        _, mapped_target = mapped
                        relative_target = os.path.relpath(
                            Path(*PurePosixPath(mapped_target).parts),
                            Path(*target_site.parts),
                        ).replace("\\", "/")
                        rewritten.append(relative_target)
                    else:
                        unresolved_lines.append(line_number)
                    continue
                candidate = (source.parent / stripped).resolve(strict=False)
                try:
                    candidate.relative_to(site_packages)
                    rewritten.append(raw_line)
                except ValueError:
                    unresolved_lines.append(line_number)
            if unresolved_lines:
                blockers.append(
                    f"unresolved absolute/path code in .pth: {group}/{rel_text} lines "
                    + ",".join(str(n) for n in unresolved_lines)
                )
                record_excluded(f"unresolved_pth:{group}")
                continue
            add_generated(target_rel, ("\n".join(rewritten) + "\n").encode("utf-8"), group)

    try:
        base = config["base_tts"]
        rvc_config = config["rvc"]
        singing_config = config.get("singing")
        tts_python = _configured_path(config_path, base["python"], "base_tts.python")
        rvc_python = _configured_path(config_path, rvc_config["python"], "rvc.python")
        tts_root = _configured_path(config_path, base["root"], "base_tts.root")
        rvc_root = _configured_path(config_path, rvc_config["root"], "rvc.root")
        ffmpeg = _configured_path(config_path, config["ffmpeg"], "ffmpeg")
        tts_env = _venv_info(tts_python, "tts")
        rvc_env = _venv_info(rvc_python, "rvc")
        singing_env = None
        if singing_config and singing_config.get("enabled"):
            singing_python = _configured_path(config_path, singing_config["python"], "singing.python")
            singing_env = _venv_info(singing_python, "singing")
    except (KeyError, TypeError, ValueError, OSError) as exc:
        raise ValueError(f"Explicit voice config could not be resolved safely: {exc}") from exc

    envs = {"tts": tts_env, "rvc": rvc_env}
    if singing_env:
        envs["singing"] = singing_env
    for label, env in envs.items():
        if not env["site_packages"].is_dir():
            blockers.append(f"{label} site-packages directory is missing")

    # Site-package roots are declared first so path-only .pth dependencies can
    # be translated to portable relative entries without leaking old paths.
    external_site_map: dict[str, tuple[Path, str]] = {}
    for label, env in envs.items():
        try:
            external_site_map[str(env["site_packages"].resolve(strict=True)).casefold()] = (
                env["site_packages"],
                (PurePosixPath(PYTHON_ROOTS[label]) / "Lib/site-packages").as_posix(),
            )
        except OSError:
            pass

    # Copy each base CPython runtime, never its venv redirector or pyvenv.cfg.
    for label, env in envs.items():
        base_root: Path = env["base_runtime"]
        target_root = PYTHON_ROOTS[label]
        match = re.match(r"^(\d+)\.(\d+)", env["base_version"])
        if not match:
            blockers.append(f"{label} Python version could not form an isolated _pth filename")
            version_tag = ""
        else:
            version_tag = f"{match.group(1)}{match.group(2)}"
        python_files = [base_root / "python.exe", base_root / "pythonw.exe"]
        python_files.extend(
            path for path in base_root.iterdir()
            if path.is_file() and re.fullmatch(r"(?i)(?:python3?\d*|vcruntime[\w.-]*)\.dll", path.name)
        )
        found_python = False
        for path in dict.fromkeys(python_files):
            if path.is_file():
                if path.name.casefold() == "python.exe":
                    found_python = True
                add_source(f"{target_root}/{path.name}", path, f"python_runtime_{label}")
        if not found_python:
            blockers.append(f"{label} CPython python.exe is missing")
        if version_tag:
            stdlib_zip = base_root / f"python{version_tag}.zip"
            if stdlib_zip.is_file():
                add_source(f"{target_root}/{stdlib_zip.name}", stdlib_zip, f"python_stdlib_zip_{label}")
            source_isolated_path = base_root / f"python{version_tag}._pth"
            if source_isolated_path.is_file():
                record_excluded(f"rewritten_base__pth:{label}")
            # Isolate Python from host registry/environment paths. Relative
            # entries select the copied standard library and site-packages.
            path_lines = []
            if stdlib_zip.is_file():
                path_lines.append(stdlib_zip.name)
            voice_module_root = os.path.relpath(
                Path("tools/robot_voice"),
                Path("tools/robot_voice", *PurePosixPath(target_root).parts),
            ).replace("\\", "/")
            path_lines.extend((".", "Lib", "DLLs", "Lib/site-packages", voice_module_root, "import site"))
            add_generated(
                f"{target_root}/python{version_tag}._pth",
                ("\n".join(path_lines) + "\n").encode("ascii"),
                f"python_isolation_{label}",
            )
            if label == "singing":
                # The first-party singing availability check derives its
                # environment as python.parent.parent and expects
                # <environment>/Lib/site-packages. Copy the base interpreter
                # into a Scripts-shaped location; do not copy the venv's
                # redirector or pyvenv.cfg.
                scripts_root = f"{target_root}/Scripts"
                for executable_name in ("python.exe", "pythonw.exe"):
                    executable = base_root / executable_name
                    if executable.is_file():
                        add_source(f"{scripts_root}/{executable_name}", executable, "singing_base_executable_compat")
                for library in base_root.iterdir():
                    if library.is_file() and re.fullmatch(
                        r"(?i)(?:python3?\d*|vcruntime[\w.-]*)\.dll", library.name
                    ):
                        add_source(f"{scripts_root}/{library.name}", library, "singing_base_executable_compat")
                scripts_module_root = os.path.relpath(
                    Path("tools/robot_voice"),
                    Path("tools/robot_voice", *PurePosixPath(scripts_root).parts),
                ).replace("\\", "/")
                scripts_lines = []
                if stdlib_zip.is_file():
                    scripts_lines.append(f"../{stdlib_zip.name}")
                scripts_lines.extend(("..", "../Lib", "../DLLs", "../Lib/site-packages", scripts_module_root, "import site"))
                add_generated(
                    f"{scripts_root}/python{version_tag}._pth",
                    ("\n".join(scripts_lines) + "\n").encode("ascii"),
                    "singing_python_isolation_scripts",
                )
        for dirname in ("DLLs", "Lib"):
            directory = base_root / dirname
            if not directory.is_dir():
                blockers.append(f"{label} CPython {dirname} is missing")
                continue
            if dirname == "Lib":
                def include_stdlib(relative: Path, _source: Path) -> bool:
                    return not (relative.parts and relative.parts[0].casefold() == "site-packages")
                copy_tree(directory, f"{target_root}/Lib", f"python_stdlib_{label}", include=include_stdlib, skip_root_dirs={"site-packages"})
            else:
                copy_tree(directory, f"{target_root}/DLLs", f"python_dlls_{label}")
        license_files = [
            path for path in base_root.iterdir()
            if path.is_file() and path.name.casefold().startswith(("license", "licence", "copying"))
        ]
        if not license_files:
            blockers.append(f"{label} CPython license file not found")
        for path in license_files:
            add_source(f"{target_root}/{path.name}", path, f"python_license_{label}")
        copy_pth_site_packages(
            env["site_packages"],
            f"{target_root}/Lib/site-packages",
            f"site_packages_{label}",
            external_site_map=external_site_map,
        )

    # Preserve the singing environment's existing shared-GPU dependency as a
    # relative .pth reference to the separately bundled TTS package tree.
    singing_site = singing_env["site_packages"] if singing_env else None
    tts_site = tts_env["site_packages"]
    shared_pth = singing_site / "shared_gpu_runtime.pth" if singing_site else None
    if shared_pth and shared_pth.is_file():
        try:
            content = shared_pth.read_text(encoding="utf-8", errors="strict")
            match = re.search(r"sys\.path\.append\(\s*(['\"])(.*?)\1\s*\)", content)
            referenced = Path(ast.literal_eval(match.group(1) + match.group(2) + match.group(1))) if match else None
            if referenced and referenced.resolve(strict=True) == tts_site.resolve(strict=True):
                tts_dest = Path(*PurePosixPath(PYTHON_ROOTS["tts"], "Lib/site-packages").parts)
                singing_dest = Path(*PurePosixPath(PYTHON_ROOTS["singing"], "Lib/site-packages").parts)
                relative = os.path.relpath(tts_dest, singing_dest).replace("\\", "/")
                add_generated(
                    f"{PYTHON_ROOTS['singing']}/Lib/site-packages/voice-shared-tts.pth",
                    (relative + "\n").encode("utf-8"),
                    "site_packages_singing_shared_tts_path",
                )
                notes.append("Singing environment's absolute shared_gpu_runtime.pth was rewritten to a relative site-packages path.")
            else:
                blockers.append("singing shared_gpu_runtime.pth did not resolve to the configured TTS site-packages")
        except (OSError, SyntaxError, ValueError):
            blockers.append("singing shared_gpu_runtime.pth could not be safely translated")
    elif singing_env:
        blockers.append("singing .pth shared TTS site-packages dependency was not found")

    # First-party service files only; do not include any QQ/AstrBot/config tree.
    actual_service_count = 0
    for name in VOICE_CODE:
        source = tools_root / name
        if source.is_file():
            actual_service_count += 1
